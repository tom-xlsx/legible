#!/usr/bin/env python3
"""Builds Bartholomew's sprite SVG from frames.txt.

Reads Resources/moth/bartholomew/frames.txt (16×16 character grids), turns each
frame into a <g id="frame-name"> of crisp pixel rects that reference the moth
palette tokens (var(--moth-*)), and writes sheet.svg plus frames.json. Themes
colour the moth through those tokens, so one sheet serves every theme. Run it
after editing frames.txt; the outputs are committed.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT / "Resources/moth/bartholomew"
SIZE = 16

TOKENS = {
    "a": "moth-body", "b": "moth-body",
    "w": "moth-wing", "s": "moth-wing-shade", "m": "moth-wing-mark",
    "e": "moth-eye-white", "p": "moth-eye", "l": "moth-eye",
    "g": "moth-glasses", "h": "moth-glasses",
    "k": "moth-book", "n": "moth-page",
}


def parse_frames(text):
    frames, name, rows = [], None, []
    for line in text.splitlines():
        if line.startswith("#") or not line.strip():
            continue
        if line.startswith("@"):
            if name:
                frames.append((name, rows))
            name, rows = line[1:].strip(), []
        else:
            rows.append(line.rstrip())
    if name:
        frames.append((name, rows))
    for fname, grid in frames:
        assert len(grid) == SIZE, f"{fname}: {len(grid)} rows, want {SIZE}"
        for r in grid:
            assert len(r) == SIZE, f"{fname}: row '{r}' is {len(r)} wide, want {SIZE}"
            for ch in r:
                assert ch == "." or ch in TOKENS, f"{fname}: unknown character '{ch}'"
    return frames


def frame_rects(grid):
    """Horizontal runs of the same colour become single rects."""
    rects = []
    for y, row in enumerate(grid):
        x = 0
        while x < SIZE:
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            end = x
            while end + 1 < SIZE and row[end + 1] == ch:
                end += 1
            rects.append(f'<rect x="{x}" y="{y}" width="{end - x + 1}" height="1" fill="var(--{TOKENS[ch]})"/>')
            x = end + 1
    return rects


def main():
    frames = parse_frames((PACK / "frames.txt").read_text())
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" width="{SIZE}" height="{SIZE}" shape-rendering="crispEdges">',
             "  <!-- Generated by scripts/pixel-moth.py from frames.txt. Each group is one frame; show one at a time. -->"]
    for name, grid in frames:
        parts.append(f'  <g id="{name}">')
        parts.extend("    " + r for r in frame_rects(grid))
        parts.append("  </g>")
    parts.append("</svg>")
    (PACK / "sheet.svg").write_text("\n".join(parts) + "\n")
    (PACK / "frames.json").write_text(json.dumps({name: i for i, (name, _) in enumerate(frames)}, indent=2) + "\n")
    print(f"Wrote {PACK / 'sheet.svg'} ({len(frames)} frames)")


if __name__ == "__main__":
    sys.exit(main())
